export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = key;
  if (lang !== 'th') {
    const row = D[key];
    if (row) s = row[lang === 'en' ? 0 : 1];
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

const LOC: Record<Lang, string> = { th: 'th-TH', en: 'en-GB', zh: 'zh-CN' };
/** '2026-12-12' -> '12 ธ.ค.' / '12 Dec' / '12月12日' */
export function dayIn(lang: Lang, iso: string): string {
  return new Date(`${iso.slice(0, 10)}T12:00:00+07:00`).toLocaleDateString(LOC[lang], { timeZone: 'Asia/Bangkok', day: 'numeric', month: 'short' });
}
export const numIn = (lang: Lang, n: number) => n.toLocaleString(LOC[lang]);
/** Language the customer picked (sent by the LIFF pages as x-lang). */
export function reqLang(req: Request): Lang { return langFrom(req.headers.get('x-lang')); }
/** t() for server routes: Thai text in, the customer's language out. */
export function serverT(req: Request) {
  const lang = reqLang(req);
  return Object.assign((key: string, vars?: Record<string, string | number>) => tr(lang, key, vars), { lang });
}

export function hasKey(key: string) { return key in D; }
export function langFrom(v: string | null | undefined): Lang {
  return v === 'en' || v === 'zh' ? v : 'th';
}
